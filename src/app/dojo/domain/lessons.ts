/** The lessons with each variant right after the one it varies, and a variant of a variant after that. */
function weave<T extends Lesson>(lessons: readonly T[], variants: readonly (readonly [string, T])[]): T[] {
  const after = (id: string): T[] =>
    variants.filter(([of]) => of === id).flatMap(([, variant]) => [variant, ...after(variant.id)]);
  return lessons.flatMap((lesson) => [lesson, ...after(lesson.id)]);
}

/** In the order they come in: what is learned first is easy and used everywhere; a variant right after its lesson. */
export const LESSONS: readonly Lesson[] = [...weave(VIM, VIM_VARIANTS), ...weave(IDE, IDE_VARIANTS)];

export const lessonById = (id: string): Lesson | undefined => LESSONS.find((lesson) => lesson.id === id);

/** A text of a lesson without its cursor mark, and the offset of the mark; null where there is none. */
export function textOf(lines: readonly string[]): { readonly text: string; readonly cursor: number | null } {
  const joined = lines.join('\n');
  const at = joined.indexOf(CURSOR);
  return { text: joined.replace(CURSOR, ''), cursor: at < 0 ? null : at };
}
