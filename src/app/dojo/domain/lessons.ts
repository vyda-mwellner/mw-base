import { fileLines } from './project';

/** Where the cursor stands in the text of a lesson: on the character after the mark. */
const CURSOR = '‸';

/** The long file of the project, for what only pays off in a long file: counts, paging, marks. */
const INVOICE = 'InvoiceService.kt';

/** A project file with the cursor on a line: at a column, or on its first character that is no space. */
function cursorIn(file: string, line: number, column?: number): string[] {
  const lines = [...fileLines(file)];
  const text = lines[line - 1];
  const at = column ?? Math.max(0, text.search(/\S/));
  lines[line - 1] = `${text.slice(0, at)}${CURSOR}${text.slice(at)}`;
  return lines;
}

type VimTopic =
  | 'Bewegen'
  | 'Springen'
  | 'Schreiben'
  | 'Löschen'
  | 'Ändern'
  | 'Kopieren'
  | 'Verschieben'
  | 'Einrücken'
  | 'Markieren'
  | 'Suchen'
  | 'Wiederholen'
  | 'Blättern';
type IdeTopic = 'Navigation' | 'Bearbeiten' | 'Suche' | 'Refactoring' | 'Werkzeuge';

/**
 * Text to change into other text, or a place to get to. `before` and `after` mark the cursor with `CURSOR`;
 * a mark in `after` means the cursor has to end up there, without one only the text counts.
 */
export interface VimLesson {
  readonly kind: 'vim';
  readonly id: string;
  readonly topic: VimTopic;
  readonly file: string;
  readonly task: string;
  readonly before: readonly string[];
  readonly after: readonly string[];
  /** The shortest usual way, in vim notation; its length is the par. */
  readonly keys: string;
  /** Normal-mode keys played before the lesson starts, for what needs a jump behind it. */
  readonly setup?: string;
  /** The text an undo brings back: the lesson starts with one change in the history. */
  readonly undoTo?: readonly string[];
  /** The text a redo brings back: the lesson starts with one change undone. */
  readonly redoTo?: readonly string[];
  /**
   * The goal turns on how many lines the editor shows, as for half a page down: the cursor has to end where
   * `keys` take it in the editor on the screen, `after` holds the text only.
   */
  readonly screen?: true;
  readonly tip: string;
}

/** Where a shortcut puts the cursor in the editor, or what it selects there. */
export type Caret = 'pageDown' | 'pageUp' | 'textStart' | 'textEnd' | 'word';

/** What a shortcut does to the line the cursor is on. */
export type LineEdit = 'duplicate' | 'delete' | 'down' | 'join';

/**
 * What a shortcut really does on the screen. `open` asks for a file through its popup, `find` for the match in
 * `file`, `structure` for a member of the file, `line` for a line number; `rename` wants `to`; `rewrite`
 * turns the start into the file as it is in the project. Without one, IntelliJ only shows the name of what it
 * would open.
 */
export type IdeEffect =
  | { readonly kind: 'open' }
  | { readonly kind: 'line'; readonly line: number }
  | { readonly kind: 'method'; readonly step: 1 | -1 }
  | { readonly kind: 'caret'; readonly to: Caret }
  | { readonly kind: 'edit'; readonly edit: LineEdit }
  | { readonly kind: 'find'; readonly query: string; readonly file: string }
  | { readonly kind: 'usages' }
  | { readonly kind: 'structure'; readonly member: string }
  | { readonly kind: 'declaration' }
  | { readonly kind: 'test' }
  | { readonly kind: 'rename'; readonly to: string }
  | { readonly kind: 'rewrite' }
  | { readonly kind: 'window'; readonly window: 'terminal' | 'run' | 'commit' }
  | { readonly kind: 'project' }
  | { readonly kind: 'hide' };

/** The file a lesson starts in, with the cursor on the first `at`; `lines` stand in for what the file holds. */
interface IdeStart {
  readonly file: string;
  readonly at?: string;
  readonly lines?: readonly string[];
}

/** A shortcut of IntelliJ IDEA with the macOS keymap. */
export interface IdeLesson {
  readonly kind: 'ide';
  readonly id: string;
  readonly topic: IdeTopic;
  /** As IntelliJ prints it: ⌃ ⌥ ⇧ ⌘ in that order, then the key. */
  readonly chord: string;
  /** The name of the action in IntelliJ. */
  readonly action: string;
  readonly task: string;
  readonly tip: string;
  readonly does?: IdeEffect;
  readonly start?: IdeStart;
}

